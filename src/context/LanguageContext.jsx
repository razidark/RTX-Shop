export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    return localStorage.getItem('language') || 'pt';
  });

  useEffect(() => {
    localStorage.setItem('language', language);
  }, [language]);

  const t = (key, replacements = {}) => {
    let text = translations[language]?.[key] || translations['pt']?.[key] || key;
    
    // Perform simple string replacements (e.g. {value})
    Object.entries(replacements).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, v);
    });
    
    return text;
  };

  const formatPrice = (value) => {
    const numericValue = typeof value === 'number' ? value : parseFloat(value);
    if (isNaN(numericValue) || numericValue === null || numericValue === undefined) {
      return language === 'pt' ? 'R$ 0,00' : '$ 0.00';
    }
    if (language === 'pt') {
      return `R$ ${numericValue.toLocaleString('pt-BR', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
    } else {
      // 1 USD = 6 BRL conversion rate
      const usdValue = numericValue / 6;
      return `$ ${usdValue.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
    }
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, formatPrice }}>
      {children}
    </LanguageContext.Provider>
  );
}

export const useLanguage = () => useContext(LanguageContext);
